import type { Program, ProgramNode, ProgramValue, ScriptWriter } from '../export/program';

/** `ExposeCommand` → `expose_command`. */
function snake(name: string): string {
  const s = name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();
  return /^[0-9]/.test(s) ? `_${s}` : s || '_';
}

function pyString(text: string): string {
  return JSON.stringify(text);   // a JSON string is a valid Python string literal
}

function value(v: ProgramValue, type: string): string {
  switch (v.kind) {
    case 'text':
      if (type === 'string') return pyString(v.text);
      if (type === 'boolean') return v.text.toLowerCase() === 'true' ? 'True' : 'False';
      return /^-?\d+(\.\d+)?$/.test(v.text) ? v.text : pyString(v.text);
    case 'query': return call(v.node);
    case 'body':  return 'None';   // mouths are written as blocks, not arguments
    case 'empty': return 'None';
  }
}

/** A call with its non-mouth arguments. */
function call(node: ProgramNode): string {
  const args = node.args.filter(a => a.value.kind !== 'body').map(a => value(a.value, a.type));
  return `${snake(node.name)}(${args.join(', ')})`;
}

function statements(body: ProgramNode[], indent: string): string[] {
  if (body.length === 0) return [`${indent}pass`];
  return body.flatMap(node => {
    const mouths = node.args.filter(a => a.value.kind === 'body');
    if (mouths.length === 0) return [`${indent}${call(node)}`];
    const inner = `${indent}    `;
    if (mouths.length === 1) {
      const m = mouths[0].value as { kind: 'body'; body: ProgramNode[] };
      return [`${indent}with ${call(node)}:`, ...statements(m.body, inner)];
    }
    // Several mouths: each under its own name.
    return [
      `${indent}with ${call(node)}:`,
      ...mouths.flatMap(m => [
        `${inner}with ${snake(m.name)}:`,
        ...statements((m.value as { kind: 'body'; body: ProgramNode[] }).body, `${inner}    `),
      ]),
    ];
  });
}

/**
 * A sample script writer for the dev app: Python, one function per chain. A start block becomes a decorated handler,
 * a block with a mouth a `with` block.
 */
export const pythonWriter: ScriptWriter = {
  id: 'python',
  label: 'Python',
  fileExtension: 'py',
  write(program: Program): string {
    const parts = program.roots.map((root, i) => {
      const [first, ...rest] = root.body;
      if (first?.blockType === 'start') {
        const args = first.args.filter(a => a.value.kind !== 'body').map(a => value(a.value, a.type));
        return [
          `@on(${[pyString(first.name), ...args].join(', ')})`,
          `def ${snake(first.name)}():`,
          ...statements(rest, '    '),
        ].join('\n');
      }
      return [`def chain_${i + 1}():`, ...statements(root.body, '    ')].join('\n');
    });
    return `# Generated by the block editor\n\n${parts.join('\n\n\n')}\n`;
  },
};
