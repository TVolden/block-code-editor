import { describe, expect, it } from 'vitest';
import type { BlockDefinition } from '../../src/types';
import type { CanvasState } from '../../src/commands/types';
import type { CommandEvent, PeerPresence } from '../../src/collaboration/types';
import { toProgram } from '../../src/export/program';
import { pythonWriter } from '../../src/demo/pythonWriter';
import { LocalServer } from '../../src/demo/LocalServer';
import { block } from '../commands/helpers';

const defs: Record<string, BlockDefinition> = {
  GameStarted: { id: 'GameStarted', name: 'GameStarted', blockType: 'start', params: [], category: 'c', color: '#000' },
  ExposeCommand: { id: 'ExposeCommand', name: 'ExposeCommand', blockType: 'command', category: 'c', color: '#000',
    params: [{ name: 'Label', type: 'string' }, { name: 'Player', type: 'Player' }, { name: 'Command', type: 'command' }] },
  Either: { id: 'Either', name: 'Either', blockType: 'command', category: 'c', color: '#000',
    params: [{ name: 'GroupA', type: 'command' }, { name: 'GroupB', type: 'command' }] },
  DrawCard: { id: 'DrawCard', name: 'DrawCard', blockType: 'command', category: 'c', color: '#000', params: [{ name: 'Count', type: 'number' }] },
  GetPlayer: { id: 'GetPlayer', name: 'GetPlayer', blockType: 'query', returnType: 'Player', category: 'c', color: '#000', params: [{ name: 'N', type: 'number' }] },
};
const slot = (fields: Partial<{ textValue: string | null; queryBlockId: string | null; commandBlockId: string | null }> = {}) =>
  ({ textValue: null, queryBlockId: null, commandBlockId: null, ...fields });

// GameStarted → ExposeCommand("Draw", GetPlayer(1)) { DrawCard(2) } → Either { } { DrawCard(_) }; and a loose DrawCard.
const canvas: CanvasState = {
  dependencies: [],
  blocks: new Map([
    block('s', { definitionId: 'GameStarted', x: 10, y: 10, nextBlockId: 'e' }),
    block('e', { definitionId: 'ExposeCommand', parentBlockId: 's', nextBlockId: 'x',
      paramSlots: [slot({ textValue: 'Draw' }), slot({ queryBlockId: 'p' }), slot({ commandBlockId: 'd' })] }),
    block('p', { definitionId: 'GetPlayer', embeddedInBlockId: 'e', embeddedSlotIndex: 1, paramSlots: [slot({ textValue: '1' })] }),
    block('d', { definitionId: 'DrawCard', embeddedInBlockId: 'e', embeddedSlotIndex: 2, paramSlots: [slot({ textValue: '2' })] }),
    block('x', { definitionId: 'Either', parentBlockId: 'e', paramSlots: [slot(), slot({ commandBlockId: 'd2' })] }),
    block('d2', { definitionId: 'DrawCard', embeddedInBlockId: 'x', embeddedSlotIndex: 1, paramSlots: [slot()] }),
    block('loose', { definitionId: 'Gone', x: 300, y: 400, paramSlots: [slot({ textValue: 'a' })] }),
  ].map(b => [b.instanceId, b])),
};

describe('toProgram', () => {
  const program = toProgram(canvas, id => defs[id]);

  it('lists the chains top to bottom, each as a sequence of blocks', () => {
    expect(program.roots.map(r => r.body.map(n => n.name))).toEqual([['GameStarted', 'ExposeCommand', 'Either'], ['Gone']]);
  });

  it('gives text, queries, mouths (empty or not) and missing definitions', () => {
    const expose = program.roots[0].body[1];
    expect(expose.args.map(a => a.value.kind)).toEqual(['text', 'query', 'body']);
    expect(expose.args[2].value).toMatchObject({ kind: 'body', body: [{ name: 'DrawCard' }] });
    const either = program.roots[0].body[2];
    expect(either.args[0].value).toEqual({ kind: 'body', body: [] });
    expect(either.args[1].value).toMatchObject({ body: [{ args: [{ value: { kind: 'empty' } }] }] });
    expect(program.roots[1].body[0]).toMatchObject({ blockType: 'missing', args: [{ name: 'param0', value: { kind: 'text', text: 'a' } }] });
  });
});

describe('pythonWriter', () => {
  it('writes handlers, calls and mouths as with-blocks', () => {
    expect(pythonWriter.write(toProgram(canvas, id => defs[id]))).toBe([
      '# Generated by the block editor',
      '',
      '@on("GameStarted")',
      'def game_started():',
      '    with expose_command("Draw", get_player(1)):',
      '        draw_card(2)',
      '    with either():',
      '        with group_a:',
      '            pass',
      '        with group_b:',
      '            draw_card(None)',
      '',
      '',
      'def chain_2():',
      '    gone("a")',
      '',
    ].join('\n'));
  });
});

describe('LocalServer', () => {
  const settle = () => new Promise(resolve => setTimeout(resolve, 0));
  const empty = (): CanvasState => ({ blocks: new Map(), dependencies: [] });

  it('sends a snapshot, then applied commands to everyone, numbered', async () => {
    const server = new LocalServer(empty());
    const a: CommandEvent[] = [], b: CommandEvent[] = [];
    const ca = server.connect('a', 'Ann', 'red'), cb = server.connect('b', 'Bo', 'blue');
    ca.commands.subscribe(e => a.push(e));
    cb.commands.subscribe(e => b.push(e));
    await settle();
    ca.commands.submit({ id: 'c1', clientId: 'a', baseVersion: 0, command: { type: 'InsertBlocks', blocks: [block('n')] } });
    await settle();
    expect(a.map(e => e.type)).toEqual(['snapshot', 'applied']);
    expect(b.map(e => e.type)).toEqual(['snapshot', 'applied']);
    expect(b[1]).toMatchObject({ version: 1, envelope: { id: 'c1' } });
    expect(server.current.state.blocks.has('n')).toBe(true);
  });

  it('rejects a command that doesn\'t apply, to the submitter only', async () => {
    const server = new LocalServer(empty());
    const a: CommandEvent[] = [], b: CommandEvent[] = [];
    const ca = server.connect('a', 'Ann', 'red'), cb = server.connect('b', 'Bo', 'blue');
    ca.commands.subscribe(e => a.push(e));
    cb.commands.subscribe(e => b.push(e));
    ca.commands.submit({ id: 'c1', clientId: 'a', baseVersion: 0, command: { type: 'MoveBlock', id: 'x', from: { x: 0, y: 0 }, to: { x: 1, y: 1 } } });
    await settle();
    expect(a.at(-1)).toMatchObject({ type: 'rejected', id: 'c1', code: 'BLOCK_NOT_FOUND' });
    expect(b.map(e => e.type)).toEqual(['snapshot']);
    expect(server.current.version).toBe(0);
  });

  it('keeps a client\'s listeners when it connects again (React StrictMode runs initializers twice)', async () => {
    const server = new LocalServer(empty());
    const first = server.connect('a', 'Ann', 'red');
    const events: CommandEvent[] = [];
    first.commands.subscribe(e => events.push(e));
    const second = server.connect('a', 'Ann', 'red');
    second.commands.submit({ id: 'c1', clientId: 'a', baseVersion: 0, command: { type: 'InsertBlocks', blocks: [block('n')] } });
    await settle();
    expect(events.map(e => e.type)).toEqual(['snapshot', 'applied']);
  });

  it('drops a disconnected client from the others\' peers and stops sending it events', async () => {
    const server = new LocalServer(empty());
    const seenByB: PeerPresence[][] = [];
    const eventsOfA: CommandEvent[] = [];
    const ca = server.connect('a', 'Ann', 'red'), cb = server.connect('b', 'Bo', 'blue');
    ca.commands.subscribe(e => eventsOfA.push(e));
    cb.presence.subscribe(peers => seenByB.push(peers));
    ca.presence.publish({ cursor: { x: 1, y: 1 }, drag: null, typing: null });
    await settle();
    server.disconnect('a');
    expect(seenByB.at(-1)).toEqual([]);
    cb.commands.submit({ id: 'c1', clientId: 'b', baseVersion: 0, command: { type: 'InsertBlocks', blocks: [block('n')] } });
    await settle();
    expect(eventsOfA.map(e => e.type)).toEqual(['snapshot']);
  });

  it('relays presence to the other clients, with name and colour', () => {
    const server = new LocalServer(empty());
    const seenByB: PeerPresence[][] = [];
    const ca = server.connect('a', 'Ann', 'red'), cb = server.connect('b', 'Bo', 'blue');
    cb.presence.subscribe(peers => seenByB.push(peers));
    ca.presence.publish({ cursor: { x: 5, y: 6 }, drag: null, typing: null });
    expect(seenByB.at(-1)).toEqual([{ clientId: 'a', name: 'Ann', color: 'red', cursor: { x: 5, y: 6 }, drag: null, typing: null }]);
  });
});
